"""The single bounded reasoning interface owned by the core."""

from typing import Protocol

from sage.coding_contracts import CodeModelRequest, CodeProposal
from sage.contracts import ProviderReadiness, ReasoningRequest, ReasoningResult


class ReasoningBackend(Protocol):
    def readiness(self) -> ProviderReadiness: ...
    async def reason(self, request: ReasoningRequest) -> ReasoningResult: ...
    async def cancel(self, request_id: str) -> None: ...
    async def aclose(self) -> None: ...


class CodingBackend(Protocol):
    def coding_readiness(self) -> ProviderReadiness: ...
    async def propose_code(self, request: CodeModelRequest) -> CodeProposal: ...
    async def cancel(self, request_id: str) -> None: ...
    async def aclose(self) -> None: ...
